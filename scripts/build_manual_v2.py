def set_paragraph_format(p, alignment=None, line_spacing=1.8):
    _set_paragraph_format(p, alignment=alignment)
    p.paragraph_format.line_spacing = line_spacing
    p.paragraph_format.space_after = Pt(4)
    # 正文首行缩进2字符（小四=12pt，2字符=24pt）
    p.paragraph_format.first_line_indent = Pt(24)

def style_runs(p, font_name=PROSE_FONT, size=BODY_SIZE):
    _style_runs(p, font_name=font_name, size=size)

# 本地 save_document：使用正确的输出目录
def save_document_local(document: Document, filename: str) -> Path:
    output = OUTPUT_DIR / filename
    try:
        document.save(str(output))
        return output
    except PermissionError:
        alt = OUTPUT_DIR / f'{output.stem}_更新版{output.suffix}'
        document.save(str(alt))
        return alt

# 本地标题：不使用 Word 内置标题样式（WPS 会加黑色方块），改用 Normal + 大字加粗
def add_heading_manual(document, text, level=1):
    p = document.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = True
    run.font.name = TITLE_FONT
    run._element.rPr.rFonts.set(qn('w:eastAsia'), TITLE_FONT)
    if level == 1:
        run.font.size = Pt(15)
    elif level == 2:
        run.font.size = Pt(13)
    else:
        run.font.size = Pt(12)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.first_line_indent = Pt(0)  # 标题不缩进
    return p

# 本地 add_image_block：用 Normal 标题替代 Heading 样式
def add_image_block(document, title, image_path, caption, width_inches):
    if not image_path.exists():
        return
    if title:
        add_heading_manual(document, title, level=2)
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.first_line_indent = Pt(0)
    run = paragraph.add_run()
    run.add_picture(str(image_path), width=Inches(width_inches))
    caption_paragraph = document.add_paragraph(caption)
    caption_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    caption_paragraph.paragraph_format.first_line_indent = Pt(0)
    style_runs(caption_paragraph)

# 本地目录：用空格缩进代替项目符号
def add_outline_toc(document, entries, title='目录'):
    add_heading_manual(document, title, level=1)
    for entry in entries:
        paragraph = document.add_paragraph(entry)
        paragraph.paragraph_format.line_spacing = 1.8
        paragraph.paragraph_format.space_after = Pt(2)
        paragraph.paragraph_format.first_line_indent = Pt(0)
        style_runs(paragraph)
    document.add_page_break()

# 本地 add_cover：使用正确的软件名称
def add_cover(document: Document, subtitle: str, note: str) -> None:
    from datetime import date
    TODAY = date(2026, 4, 16)
    p = document.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(SOFTWARE_NAME)
    run.bold = True
    run.font.size = Pt(20)
    run.font.name = TITLE_FONT
    run._element.rPr.rFonts.set(qn('w:eastAsia'), TITLE_FONT)

    p = document.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(subtitle)
    run.bold = True
    run.font.size = Pt(16)
    run.font.name = TITLE_FONT
    run._element.rPr.rFonts.set(qn('w:eastAsia'), TITLE_FONT)

    document.add_paragraph('')
    document.add_paragraph('')

    table = document.add_table(rows=0, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'
    from docx.oxml import OxmlElement
    info = [
        ('软件简称', SOFTWARE_SHORT_NAME),
        ('版本号', SOFTWARE_VERSION),
        ('运行平台', 'Android'),
        ('文档性质', note),
        ('生成日期', TODAY.strftime('%Y年%m月%d日')),
    ]
    for key, value in info:
        row = table.add_row().cells
        row[0].text = key
        row[1].text = value
        for idx, cell in enumerate(row):
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if idx == 0:
                tc_pr = cell._tc.get_or_add_tcPr()
                shd = OxmlElement('w:shd')
                shd.set(qn('w:fill'), 'EAF2F8')
                tc_pr.append(shd)
    document.add_page_break()

