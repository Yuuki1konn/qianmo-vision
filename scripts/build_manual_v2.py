def build_source_doc_v2() -> Path:
    """V2: 匹配APP源码模板.docx格式——无行号、无文件清单、宽页边距。"""
    doc = Document()

    # 匹配模板页面设置：宽页边距
    section = doc.sections[0]
    section.top_margin = Cm(2.1)
    section.bottom_margin = Cm(2.1)
    section.left_margin = Cm(3.2)
    section.right_margin = Cm(3.2)
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)

    configure_styles(doc)

    # 匹配模板页眉：左对齐，软件名称+版本
    header = section.header
    hp = header.paragraphs[0]
    hp.alignment = WD_ALIGN_PARAGRAPH.LEFT
    hp.text = f'{SOFTWARE_NAME}{SOFTWARE_VERSION}'
    style_runs(hp, PROSE_FONT, BODY_SIZE)

    # 页脚留空
    footer = section.footer
    footer.paragraphs[0].text = ''

    # 收集所有源文件
    all_files = list(SOURCE_FILES) + [ROOT / f for f in [
        'android/app/src/main/AndroidManifest.xml',
        'android/app/src/main/res/layout/activity_main.xml',
        'android/app/src/main/res/values/strings.xml',
        'android/app/src/main/res/values/themes.xml',
    ]]
    all_relative = [f.relative_to(ROOT) if f.is_absolute() else f for f in all_files]

    # 读取每个文件，收集代码行
    entries: list[SourceEntry] = []
    line_number = 1
    for relative_path in all_relative:
        path = ROOT / relative_path
        in_block_comment = False
        for raw_line in path.read_text(encoding='utf-8').splitlines():
            stripped = raw_line.strip()
            if not stripped:
                entries.append(SourceEntry(line_number, ''))
                line_number += 1
                continue
            if in_block_comment:
                if '*/' in stripped:
                    in_block_comment = False
                continue
            if stripped.startswith('/*'):
                if '*/' not in stripped:
                    in_block_comment = True
                continue
            if stripped.startswith('<!--'):
                if '-->' not in stripped:
                    continue
            entries.append(SourceEntry(line_number, raw_line.rstrip()))
            line_number += 1

    # 前30页 + 后30页 交存策略
    max_lines = SOURCE_LINES_PER_PAGE * SOURCE_MAX_PAGES
    if len(entries) > max_lines:
        head_count = SOURCE_LINES_PER_PAGE * 30
        tail_count = SOURCE_LINES_PER_PAGE * 30
        selected = entries[:head_count] + entries[-tail_count:]
    else:
        selected = entries

    # 按每页50行分块，输出纯代码（无行号、无文件清单）
    chunks = list(chunked(selected, SOURCE_LINES_PER_PAGE))
    for chunk_index, chunk in enumerate(chunks):
        for entry in chunk:
            paragraph = doc.add_paragraph()
            paragraph.paragraph_format.space_before = Pt(0)
            paragraph.paragraph_format.space_after = Pt(0)
            paragraph.paragraph_format.line_spacing = Pt(10.2)

            code_run = paragraph.add_run(entry.text)
            code_run.font.name = CODE_FONT
            code_run._element.rPr.rFonts.set(qn('w:eastAsia'), CODE_FONT)
            code_run.font.size = Pt(7.2)

        if chunk_index < len(chunks) - 1:
            doc.add_page_break()

    return save_document_local(doc, '源程序鉴别材料.docx')


